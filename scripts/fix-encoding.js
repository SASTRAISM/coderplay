function fixFile(filePath) {
  let content = fs.readFileSync(filePath)
  let hasNonAscii = false
  for (const b of content) { if (b > 127) { hasNonAscii = true; break } }
  if (!hasNonAscii) return
  const original = content
  for (const [find, repl] of PAIRS) {
    let idx, start = 0, parts = []
    while ((idx = content.indexOf(find, start)) !== -1) {
      parts.push(content.slice(start, idx), repl)
      start = idx + find.length
    }
    if (parts.length) { parts.push(content.slice(start)); content = Buffer.concat(parts) }
  }
  // fallback: any remaining non-ASCII byte -> '?'
  for (let i = 0; i < content.length; i++) if (content[i] > 127) content[i] = 0x3f
  if (!content.equals(original)) fs.writeFileSync(filePath, content)
}

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (!['node_modules','.next','dist','.git'].includes(entry.name)) walk(full)
    } else if (/\.(tsx?|jsx?)$/.test(entry.name)) {
      fixFile(full)
    }
  }
}

